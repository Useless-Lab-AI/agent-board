async page => {
  const check = (value, message) => { if (!value) throw new Error(message); };
  const loaded = count => page.waitForFunction(count => document.querySelectorAll('article').length === count && [...document.querySelectorAll('article')].every(c => c.querySelector('[data-event-id]')), count);
  const bottom = () => page.waitForFunction(() => [...document.querySelectorAll('article [tabindex="0"]')].every(e => Math.abs(e.scrollHeight - e.scrollTop - e.clientHeight) <= 2));
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto('http://127.0.0.1:4318');
  await loaded(12);
  await bottom();
  const firstIds = await page.locator('article').evaluateAll(cards => cards.map(c => c.dataset.sessionId));
  await page.getByRole('button', { name: '加载更多会话', exact: true }).click();
  await loaded(24);
  await bottom();
  check(JSON.stringify((await page.locator('article').evaluateAll(cards => cards.map(c => c.dataset.sessionId))).slice(0, 12)) === JSON.stringify(firstIds), 'Stable order on load more');
  await page.getByRole('combobox', { name: '来源', exact: true }).selectOption('codex');
  await loaded(12);
  await bottom();
  const named = page.locator('article').filter({ has: page.getByRole('heading', { name: '合成会话名称 23', exact: true }) });
  check(await named.count() === 1, 'Native title visible');
  check((await named.locator('header h3').getAttribute('title')).includes('合成会话名称 23'), 'Full title tooltip');
  await page.setViewportSize({ width: 375, height: 812 });
  await bottom();
  check(await page.evaluate(() => document.documentElement.scrollWidth <= 375), 'Mobile fits');
  await page.screenshot({ path: 'docs/card-polish-mobile-synthetic.png' });
  await page.setViewportSize({ width: 1440, height: 900 });
  await bottom();
  const viewport = named.locator('[tabindex="0"]');
  await viewport.evaluate(el => { el.scrollTop = 200; el.dispatchEvent(new Event('scroll')); });
  await page.getByRole('button', { name: '刷新会话', exact: true }).click();
  await page.waitForTimeout(800);
  check(await viewport.evaluate(el => el.scrollTop) === 200, 'Manual pause survives refresh');
  await viewport.evaluate(el => { el.scrollTop = 0; el.dispatchEvent(new Event('scroll')); });
  const firstEvent = named.locator('[data-event-id]').first();
  const anchor = await firstEvent.evaluate(el => ({ id: el.dataset.eventId, top: el.getBoundingClientRect().top - el.closest('[tabindex]').getBoundingClientRect().top }));
  const previousCount = await named.locator('[data-event-id]').count();
  await named.getByRole('button', { name: '加载更早记录' }).click();
  await page.waitForFunction(({ id, previousCount }) => document.querySelector(`article[data-session-id="${id}"]`).querySelectorAll('[data-event-id]').length > previousCount, { id: await named.getAttribute('data-session-id'), previousCount });
  const after = await named.locator(`[data-event-id="${anchor.id}"]`).evaluate(el => el.getBoundingClientRect().top - el.closest('[tabindex]').getBoundingClientRect().top);
  check(Math.abs(after - anchor.top) <= 2, 'Older history preserves visible anchor');
  const pausedTop = await viewport.evaluate(el => el.scrollTop);
  await named.getByRole('button', { name: '展开会话' }).click();
  await page.waitForFunction(() => { const el = document.querySelector('dialog[open] [tabindex="0"]'); return el && Math.abs(el.scrollHeight - el.scrollTop - el.clientHeight) <= 2; });
  await page.keyboard.press('Escape');
  check(await viewport.evaluate(el => el.scrollTop) === pausedTop, 'Dialog does not move paused card');
  check(await named.getByRole('button', { name: '展开会话' }).evaluate(el => el === document.activeElement), 'Dialog restores focus');
  await page.screenshot({ path: 'docs/card-polish-desktop-synthetic.png' });
  // Leave a known native synthetic card paused for the external append/SSE check.
  await viewport.evaluate(el => { el.scrollTop = 200; el.dispatchEvent(new Event('scroll')); });
  return { passed: ['12 initial', '24 on load more', 'filter resets12', 'native titles', 'all cards bottom', 'resize follow', 'manual pause', 'history anchor', 'modal bottom/focus'], appendTarget: 'synthetic-23', pausedTop: 200 };
}
