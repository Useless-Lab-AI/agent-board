async page => {
  const check = (ok, message) => { if (!ok) throw new Error(message); };
  await page.setViewportSize({width:1440,height:900});
  await page.goto('http://127.0.0.1:4318');
  await page.locator('article').first().getByRole('button',{name:'标记已读'}).waitFor();
  await page.waitForFunction(()=>document.querySelectorAll('article [data-event-id]').length>20);
  const dimensions=await page.locator('article').evaluateAll(cards=>cards.map(c=>{const b=c.getBoundingClientRect();return {width:b.width,height:b.height,top:b.top};}));
  check(dimensions.length===3,'Three cards visible');
  check(dimensions.every(d=>d.width===420&&d.height===560&&d.top===dimensions[0].top),'420x560 aligned cards');
  check(await page.evaluate(()=>!window.__unsafe&&!document.querySelector('img')),'No raw HTML or image loading');
  const first=page.locator('article').first();
  const second=page.locator('article').nth(1);
  const secondTop=await second.locator('[tabindex="0"]').evaluate(el=>el.scrollTop);
  await first.locator('[tabindex="0"]').evaluate(el=>{el.scrollTop=0;el.dispatchEvent(new Event('scroll'));});
  check(await second.locator('[tabindex="0"]').evaluate(el=>el.scrollTop)===secondTop,'Independent scroll');
  const id=await first.getAttribute('data-session-id');
  await first.getByRole('button',{name:'标记已读'}).click();
  await page.waitForFunction(id=>document.querySelector(`article[data-session-id="${id}"] [data-state="READ"]`),id);
  await page.reload();
  await page.waitForFunction(id=>document.querySelector(`article[data-session-id="${id}"] [data-state="READ"]`),id);
  const card=page.locator(`article[data-session-id="${id}"]`);
  await card.getByRole('button',{name:'展开会话'}).click();
  check(await page.locator('dialog[open]').count()===1,'Expanded reading dialog');
  await page.keyboard.press('Escape');
  check(await page.locator('dialog[open]').count()===0,'Escape closes dialog');
  check(await card.getByRole('button',{name:'展开会话'}).evaluate(el=>el===document.activeElement),'Dialog focus return');
  await card.getByRole('button',{name:'收纳',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('article').length===2);
  await page.getByRole('button',{name:'已收纳会话',exact:true}).click();
  await page.locator(`article[data-session-id="${id}"]`).getByRole('button',{name:'移回看板'}).click();
  await page.getByRole('button',{name:'会话看板',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('article').length===3);
  await page.getByRole('combobox',{name:'来源',exact:true}).selectOption('claude');
  await page.waitForFunction(()=>document.querySelectorAll('article').length===1);
  await page.getByRole('combobox',{name:'来源',exact:true}).selectOption('');
  await page.waitForFunction(()=>document.querySelectorAll('article').length===3);
  await page.screenshot({path:'docs/board-desktop-synthetic.png'});
  await page.setViewportSize({width:375,height:812});
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=375),'No mobile horizontal overflow');
  const mobile=await page.locator('article').first().boundingBox();
  check(mobile.width<=347&&mobile.height===560,'Mobile card fits viewport');
  await page.screenshot({path:'docs/board-mobile-synthetic.png'});
  await page.setViewportSize({width:1440,height:900});
  console.log('PASS browser: desktop/mobile geometry, independent scroll, read persistence, archive/unarchive, filters, accessible dialog, safe Markdown');
}
